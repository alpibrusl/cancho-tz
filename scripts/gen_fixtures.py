#!/usr/bin/env python3
"""Regenerate tests/fixtures/zone_data.cho: real TZif files from the system zoneinfo, as hex, plus one synthetic file.

    python3 -I scripts/gen_fixtures.py [--zoneinfo /usr/share/zoneinfo]

The synthetic file is Europe/Madrid with two leap-second records inserted in both data blocks (version 1: 8 bytes each,
version 2: 12 bytes each, before the standard/wall and UT/local indicator arrays), because no leap-second zone file ("right/")
is installed here and the code that skips those records must still be exercised. Its answers are Madrid's: leap seconds are
skipped, not applied.
"""
import argparse
import struct

ZONES = ["Europe/Madrid", "Europe/Lisbon", "America/New_York", "Asia/Tokyo", "Asia/Kolkata", "Australia/Lord_Howe",
         "Australia/Sydney", "Europe/Dublin", "Pacific/Apia", "America/Nuuk", "Africa/Casablanca", "UTC"]


def with_leap_records(data, extra=2):
    """Madrid with `extra` leap-second records inserted in each data block and the counts raised."""
    def split(block_start, wide):
        isut, isstd, leap, timecnt, typecnt, charcnt = struct.unpack(">6l", data[block_start + 20 : block_start + 44])
        tsz = 8 if wide else 4
        body = block_start + 44
        after_chars = body + timecnt * tsz + timecnt + typecnt * 6 + charcnt
        rec = 12 if wide else 8
        end = after_chars + leap * rec + isstd + isut
        return (isut, isstd, leap, timecnt, typecnt, charcnt), body, after_chars, rec, end
    c1, body1, ac1, rec1, end1 = split(0, False)
    out = bytearray(data[:28])
    out += struct.pack(">l", c1[2] + extra) + data[32:44]
    out += data[44:ac1]
    for k in range(extra):
        out += struct.pack(">ll", 78796800 + k * 15768000, 1 + k)
    out += data[ac1:end1]
    h2 = end1
    c2, body2, ac2, rec2, end2 = split(h2, True)
    out += data[h2 : h2 + 28] + struct.pack(">l", c2[2] + extra) + data[h2 + 32 : h2 + 44]
    out += data[h2 + 44 : ac2]
    for k in range(extra):
        out += struct.pack(">ql", 78796800 + k * 15768000, 1 + k)
    out += data[ac2:]
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zoneinfo", default="/usr/share/zoneinfo")
    ap.add_argument("--out", default="tests/fixtures/zone_data.cho")
    args = ap.parse_args()
    out = ["edition 5;", "", "module zone_data;", "",
           "// Real TZif files from the system tzdata (see /usr/share/zoneinfo/+VERSION), as lower-case hex, so a pure test can use a",
           "// zone without reading a file; plus one synthetic file (madrid_with_leap_records). Generated by scripts/gen_fixtures.py.",
           "// The expected values in the tests were computed with Python's zoneinfo, which reads the same files.", ""]
    for z in ZONES:
        b = open("%s/%s" % (args.zoneinfo, z), "rb").read()
        fn = z.lower().replace("/", "_")
        out += ["// %s: %d bytes" % (z, len(b)), "pub fn %s() -> [] &static [byte] {" % fn, '    return "%s";' % b.hex(), "}", ""]
        if z == "Europe/Madrid":
            s = with_leap_records(b)
            out += ["// Europe/Madrid with two leap-second records in each data block: %d bytes" % len(s),
                    "pub fn madrid_with_leap_records() -> [] &static [byte] {", '    return "%s";' % s.hex(), "}", ""]
    open(args.out, "w").write("\n".join(out))


if __name__ == "__main__":
    main()
